#!/usr/bin/env python3
"""
Builds integrations/byteforge/hubtech-platform.css: ByteForge's own stylesheet recoloured to the
HUBTECH look (ByteForge purple instead of orange, navy glass instead of grey, Manrope type).
hubtech-theme.js swaps it in only when the panel runs inside HUBTECH, so ByteForge on its own is unchanged.

Run:  python3 tools/build_byteforge_theme.py
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BF = ROOT / "integrations" / "byteforge"
SRC, OUT = BF / "byteforge-platform.css", BF / "hubtech-platform.css"

COLORS = [
    ("255,107,26", "162,89,255"), ("255, 107, 26", "162, 89, 255"),
    ("#FF6B1A", "#A259FF"), ("#ff6b1a", "#a259ff"), ("#FF9A3C", "#C49BFF"), ("#ff9a3c", "#c49bff"), ("#CC4E00", "#7C3AED"), ("#E55A0F", "#7C3AED"), ("#e55a0f", "#7c3aed"), ("#070707", "#08111f"),
    ("rgba(22,22,22,", "rgba(12,22,38,"), ("rgba(8,8,8,", "rgba(5,10,20,"),
    ("#0D0D0D", "#0b1626"), ("#111111", "#0f1c30"), ("#1A1A1A", "#15243b"), ("#242424", "#1d2d47"), ("#2E2E2E", "#26385a"),
    ("--t:#F5F0E8", "--t:#eef4fb"), ("--t2:#888880", "--t2:#9fb0c4"), ("--t3:#555555", "--t3:#6b7d94"),
]
FONTS = "\n".join(
    f"@font-face{{font-family:'Manrope';font-style:normal;font-weight:{w};font-display:swap;src:url(hubtech-manrope-{w}.woff2) format('woff2')}}"
    for w in (500, 600, 700, 800))
EXTRA = """
/* ── HUBTECH: Manrope everywhere, softer radii and glass ── */
:root{--display:'Manrope',sans-serif;--body:'Manrope',sans-serif;--radius:14px;--blur:14px;--ls:.5px}
html,body{background:#0b1626}
body::after{background:radial-gradient(ellipse 70% 60% at 85% 0%,rgba(162,89,255,.12) 0%,transparent 70%),radial-gradient(ellipse 60% 60% at 0% 100%,rgba(47,140,255,.08) 0%,transparent 70%)}
.login-brand{letter-spacing:1px;font-weight:800}
::-webkit-scrollbar-thumb{background:rgba(162,89,255,.6);border-radius:8px}
"""


def main():
    css = SRC.read_text(encoding="utf-8")
    css = re.sub(r"@import url\('https://fonts\.googleapis\.com[^)]*'\);", "", css)
    for a, b in COLORS:
        css = css.replace(a, b)
    OUT.write_text("/* Generated by tools/build_byteforge_theme.py – do not edit */\n" + FONTS + "\n" + css + EXTRA, encoding="utf-8")
    for w in (500, 600, 700, 800):
        shutil.copyfile(ROOT / "web" / "fonts" / f"manrope-latin-{w}-normal.woff2", BF / f"hubtech-manrope-{w}.woff2")
    print(f"Skrev {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
